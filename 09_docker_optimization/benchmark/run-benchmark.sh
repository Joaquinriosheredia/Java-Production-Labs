#!/usr/bin/env bash
set -euo pipefail
echo "=== Lab 09 — Docker Optimization Benchmark ==="
cd "$(dirname "$0")/.."

RAW=benchmark/results/raw
rm -rf "$RAW" && mkdir -p "$RAW"
bash ../scripts/bench-env.sh "$RAW/env.txt"

now() { date +%s.%N; }
elapsed() { python3 -c "print(f'{$2-$1:.1f}')"; }

# The naive Dockerfile copies a pre-built jar from target/.
echo ""
echo "--- Building jar for the NAIVE image ---"
./mvnw -q package -DskipTests

echo ""
echo "--- Building NAIVE image ---"
docker build -q -f docker/Dockerfile.naive -t lab09-naive . > /dev/null

echo ""
echo "--- Building OPTIMIZED image ---"
docker build -q -f docker/Dockerfile -t lab09-optimized . > /dev/null

# A real code-only change: touching the file is not enough, because Docker
# caches COPY by content, not mtime. Append a comment, rebuild, then restore.
echo ""
echo "--- Code-only rebuild (optimized) ---"
SRC=app/src/main/java/com/labs/dockeropt/DockerOptimizationApplication.java
cp "$SRC" "$RAW/.src.bak"
echo "// rebuild probe $(date +%s)" >> "$SRC"
t0=$(now)
docker build -q -f docker/Dockerfile -t lab09-optimized-rebuild . > /dev/null
t1=$(now)
cp "$RAW/.src.bak" "$SRC" && rm "$RAW/.src.bak"
REBUILD_S=$(elapsed "$t0" "$t1")

for img in lab09-naive lab09-optimized; do
  docker image inspect "$img" > "$RAW/$img.inspect.json"
done
docker history --no-trunc --format '{{.Size}}\t{{.CreatedBy}}' lab09-optimized > "$RAW/lab09-optimized.history.txt"

size_mb() { docker image inspect "$1" --format='{{.Size}}' | awk '{printf "%.0f", $1/1000/1000}'; }
user_of() { u=$(docker image inspect "$1" --format='{{.Config.User}}'); echo "${u:-root (no USER)}"; }
uid_of() { docker run --rm --entrypoint id "$1" -u 2>/dev/null || echo "n/a"; }
NAIVE_MB=$(size_mb lab09-naive); OPT_MB=$(size_mb lab09-optimized)
REDUCTION=$(python3 -c "print(f'{(1-$OPT_MB/$NAIVE_MB)*100:.0f}')")

{
  echo "# Lab 09 — Benchmark results"
  echo
  echo "Generated by \`benchmark/run-benchmark.sh\`. Raw data: \`results/raw/\` (image inspect, layer history)."
  echo
  echo "## Environment"
  echo
  echo '```'
  cat "$RAW/env.txt"
  echo '```'
  echo
  echo "## Results"
  echo
  echo "Sizes are \`docker image inspect .Size\` in MB (10^6 bytes)."
  echo
  echo "| Metric | Naive (\`Dockerfile.naive\`) | Optimized (\`Dockerfile\`) |"
  echo "|---|---|---|"
  echo "| Base image | \`eclipse-temurin:21-jdk\` | \`eclipse-temurin:21-jre-alpine\` |"
  echo "| Image size | ${NAIVE_MB} MB | ${OPT_MB} MB (−${REDUCTION} %) |"
  echo "| Runs as | $(user_of lab09-naive) (uid $(uid_of lab09-naive)) | $(user_of lab09-optimized) (uid $(uid_of lab09-optimized)) |"
  echo "| Code-only rebuild (one Java file changed, warm cache) | not measured | ${REBUILD_S} s |"
  echo
  echo "Not measured by this script: startup time, naive rebuild time."
} > benchmark/results/summary.md

cat benchmark/results/summary.md
