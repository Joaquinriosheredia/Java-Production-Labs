#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"

BASE_URL="${BASE_URL:-http://localhost:8080}"
TASKS="${TASKS:-200}"
LATENCY_MS="${LATENCY_MS:-100}"
POOL_SIZE="${POOL_SIZE:-20}"
RUNS="${RUNS:-5}"
VUS_LIST="${VUS_LIST:-50 200}"

echo "============================================"
echo " Lab 01 — Virtual Threads Benchmark"
echo " Base URL  : $BASE_URL"
echo " Tasks     : $TASKS"
echo " Latency   : ${LATENCY_MS}ms per task"
echo " Runs      : $RUNS per mode and load"
echo " VUs       : $VUS_LIST"
echo "============================================"

if ! command -v k6 &>/dev/null; then
  echo "ERROR: k6 is not installed. Install from https://k6.io/docs/get-started/installation/"
  exit 1
fi

RAW=results/raw
rm -rf "$RAW" && mkdir -p "$RAW"
bash ../../scripts/bench-env.sh "$RAW/env.txt"

run_mode() {
  local mode="$1" run="$2" vus="$3"
  # Exit code 99 = a k6 threshold failed; the run is still recorded.
  k6 run --quiet \
    --env VUS="$vus" \
    --env BASE_URL="$BASE_URL" \
    --env TASKS="$TASKS" \
    --env LATENCY_MS="$LATENCY_MS" \
    --env MODE="$mode" \
    --env POOL_SIZE="$POOL_SIZE" \
    --summary-trend-stats "avg,min,med,max,p(95),p(99)" \
    --summary-export "$RAW/vus${vus}/${mode}_run${run}.json" \
    load-test.js || [ $? -eq 99 ]
}

# Modes alternate within each run so drift (thermal, background load) hits both equally.
for vus in $VUS_LIST; do
  mkdir -p "$RAW/vus$vus"
  for run in $(seq 1 "$RUNS"); do
    echo ""; echo "--- VUs $vus, run $run/$RUNS: virtual ---";  run_mode virtual "$run" "$vus"
    echo ""; echo "--- VUs $vus, run $run/$RUNS: platform (pool=$POOL_SIZE) ---"; run_mode platform "$run" "$vus"
  done
done

stat() { python3 ../../scripts/bench_stats.py "$1" $RAW/vus"$3"/"$2"_run*.json; }
row() {
  local vus="$1" label="$2" path="$3"
  read -r vm vmin vmax _ <<<"$(stat "$path" virtual "$vus")"
  read -r pm pmin pmax _ <<<"$(stat "$path" platform "$vus")"
  echo "| $vus | $label | $vm ($vmin – $vmax) | $pm ($pmin – $pmax) |"
}

{
  echo "# Lab 01 — Benchmark results"
  echo
  echo "Generated by \`benchmark/run-benchmark.sh\`. Raw k6 summaries: \`results/raw/\`."
  echo
  echo "## Environment"
  echo
  echo '```'
  cat "$RAW/env.txt"
  echo '```'
  echo
  echo "Parameters: $RUNS runs per mode and load; k6 stages in \`load-test.js\` (10 s ramp-up, 30 s steady at the given VUs, 10 s ramp-down); tasks=$TASKS, latency=${LATENCY_MS} ms, platform pool=$POOL_SIZE."
  echo "Compare modes within the same load only: the loads are different experiments."
  echo
  echo "## Results — median (min – max) over $RUNS runs"
  echo
  echo "| VUs | Metric | Virtual threads | Platform threads (pool=$POOL_SIZE) |"
  echo "|---|---|---|---|"
  for vus in $VUS_LIST; do
    row "$vus" "Throughput (req/s)" "metrics.http_reqs.rate"
    row "$vus" "p50 latency (ms)" "metrics.http_req_duration.med"
    row "$vus" "p95 latency (ms)" "metrics.http_req_duration.p(95)"
    row "$vus" "p99 latency (ms)" "metrics.http_req_duration.p(99)"
    row "$vus" "Error rate" "metrics.error_rate.value"
  done
} > results/summary.md

echo ""
cat results/summary.md
