#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"

BASE_URL="${BASE_URL:-http://localhost:8080}"
TASKS="${TASKS:-200}"
LATENCY_MS="${LATENCY_MS:-100}"
POOL_SIZE="${POOL_SIZE:-20}"
RUNS="${RUNS:-5}"

echo "============================================"
echo " Lab 01 — Virtual Threads Benchmark"
echo " Base URL  : $BASE_URL"
echo " Tasks     : $TASKS"
echo " Latency   : ${LATENCY_MS}ms per task"
echo " Runs      : $RUNS per mode"
echo "============================================"

if ! command -v k6 &>/dev/null; then
  echo "ERROR: k6 is not installed. Install from https://k6.io/docs/get-started/installation/"
  exit 1
fi

RAW=results/raw
rm -rf "$RAW" && mkdir -p "$RAW"
bash ../../scripts/bench-env.sh "$RAW/env.txt"

run_mode() {
  local mode="$1" run="$2"
  k6 run --quiet \
    --env BASE_URL="$BASE_URL" \
    --env TASKS="$TASKS" \
    --env LATENCY_MS="$LATENCY_MS" \
    --env MODE="$mode" \
    --env POOL_SIZE="$POOL_SIZE" \
    --summary-trend-stats "avg,min,med,max,p(95),p(99)" \
    --summary-export "$RAW/${mode}_run${run}.json" \
    load-test.js
}

# Modes alternate within each run so drift (thermal, background load) hits both equally.
for run in $(seq 1 "$RUNS"); do
  echo ""; echo "--- Run $run/$RUNS: virtual ---";  run_mode virtual "$run"
  echo ""; echo "--- Run $run/$RUNS: platform (pool=$POOL_SIZE) ---"; run_mode platform "$run"
done

stat() { python3 ../../scripts/bench_stats.py "$1" $RAW/"$2"_run*.json; }
row() {
  local label="$1" path="$2"
  read -r vm vmin vmax _ <<<"$(stat "$path" virtual)"
  read -r pm pmin pmax _ <<<"$(stat "$path" platform)"
  echo "| $label | $vm ($vmin – $vmax) | $pm ($pmin – $pmax) |"
}

{
  echo "# Lab 01 — Benchmark results"
  echo
  echo "Generated by \`benchmark/run-benchmark.sh\`. Raw k6 summaries: \`results/raw/\`."
  echo
  echo "## Environment"
  echo
  echo '```'
  cat "$RAW/env.txt"
  echo '```'
  echo
  echo "Parameters: $RUNS runs per mode, k6 stages in \`load-test.js\` (50 VUs steady), tasks=$TASKS, latency=${LATENCY_MS} ms, platform pool=$POOL_SIZE."
  echo
  echo "## Results — median (min – max) over $RUNS runs"
  echo
  echo "| Metric | Virtual threads | Platform threads (pool=$POOL_SIZE) |"
  echo "|---|---|---|"
  row "Throughput (req/s)" "metrics.http_reqs.rate"
  row "p50 latency (ms)" "metrics.http_req_duration.med"
  row "p95 latency (ms)" "metrics.http_req_duration.p(95)"
  row "p99 latency (ms)" "metrics.http_req_duration.p(99)"
  row "Error rate" "metrics.error_rate.value"
} > results/summary.md

echo ""
cat results/summary.md
